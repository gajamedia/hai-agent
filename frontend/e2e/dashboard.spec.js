
import { test, expect } from "@playwright/test";

const apiBaseURL =
  process.env.E2E_API_BASE_URL || "http://127.0.0.1:8000";

const enableMutatingTests =
  process.env.E2E_ENABLE_MUTATING_TESTS === "1";

test.describe("hAI Agent Dashboard E2E smoke tests", () => {
  test("Dashboard loads in a real browser", async ({ page }) => {
    const pageErrors = [];

    page.on("pageerror", (error) => {
      pageErrors.push(error.message);
    });

    await page.goto("/");

    await expect(
      page.getByText("hAI Agent", { exact: true }).first(),
    ).toBeVisible();

    await expect(
      page.getByRole("button", { name: "Plan & Run Goal" }),
    ).toBeVisible();

    expect(pageErrors).toEqual([]);
  });

  test("backend health endpoint responds successfully", async ({
    request,
  }) => {
    const response = await request.get(`${apiBaseURL}/health`);

    expect(response.status()).toBe(200);

    const body = await response.json();
    expect(body.status).toBe("ok");
    expect(body.service).toBe("hai-agent-api");
  });

  test("execution state endpoint responds successfully", async ({
    request,
  }) => {
    const response = await request.get(
      `${apiBaseURL}/api/v1/execution/state`,
    );

    expect(response.status()).toBe(200);

    const body = await response.json();

    expect(body.status).toBe("ok");
    expect(body.state).toBeTruthy();
    expect(body.allowed_actions).toEqual(
      expect.arrayContaining([
        "open_box",
        "take_key",
        "find_spare_key",
        "unlock_door",
      ]),
    );
  });
});

test.describe("hAI Agent goal execution E2E", () => {
  test.skip(
    !enableMutatingTests,
    "Mutating tests require E2E_ENABLE_MUTATING_TESTS=1 and a dedicated local test environment.",
  );

  test("executes a goal through the browser and replays the same idempotency key safely", async ({
    page,
    request,
  }) => {
    // Reset only the local simulation. Use a dedicated test backend/database.
    const resetResponse = await request.post(
      `${apiBaseURL}/api/v1/execution/reset`,
    );

    expect(
      resetResponse.status(),
      "The dedicated test simulation must reset successfully.",
    ).toBe(200);

    await page.goto("/");

    const runButton = page.getByRole("button", {
      name: "Plan & Run Goal",
    });

    await expect(runButton).toBeVisible();
    await expect(runButton).toBeEnabled();

    // Capture the actual request generated by the Dashboard.
    const requestPromise = page.waitForRequest((candidate) => {
      return (
        candidate.method() === "POST" &&
        new URL(candidate.url()).pathname ===
          "/api/v1/execution/plan-run"
      );
    });

    const responsePromise = page.waitForResponse((response) => {
      return (
        response.request().method() === "POST" &&
        new URL(response.url()).pathname ===
          "/api/v1/execution/plan-run"
      );
    });

    await runButton.click();

    const browserRequest = await requestPromise;
    const browserResponse = await responsePromise;

    expect(
      browserRequest.postData(),
      "The browser must send a JSON request body.",
    ).toBeTruthy();

    const payload = browserRequest.postDataJSON();
    const headers = await browserRequest.allHeaders();
    const idempotencyKey = headers["idempotency-key"];

    expect(payload).toEqual(
      expect.objectContaining({
        observation: expect.anything(),
        goal_description: expect.any(String),
        target_state: expect.any(Object),
        actions: expect.any(Array),
      }),
    );

    expect(payload.goal_description.trim().length).toBeGreaterThan(0);
    expect(Object.keys(payload.target_state).length).toBeGreaterThan(0);
    expect(idempotencyKey).toBeTruthy();

    // The API response must be successful before replay is tested.
    expect(
      browserResponse.status(),
      "Plan-run did not return a successful HTTP response.",
    ).toBe(200);

    const firstResult = await browserResponse.json();

    expect(firstResult.idempotency).toEqual({
      key: idempotencyKey,
      replayed: false,
    });

    expect(firstResult.goal).toBeTruthy();
    expect(firstResult.execution).toBeTruthy();

    // UI must reflect goal verification, not just execution success.
    await expect(page.getByText("GOAL VERIFICATION")).toBeVisible();

    if (firstResult.goal.satisfied === true) {
      await expect(page.getByText("Goal tercapai")).toBeVisible();
      await expect(page.getByText("Lulus")).toBeVisible();
    } else if (firstResult.execution.success === true) {
      await expect(
        page.getByText("Aksi selesai, goal belum tercapai"),
      ).toBeVisible();
      await expect(page.getByText("Belum lulus")).toBeVisible();
    } else {
      await expect(page.getByText("Belum tercapai")).toBeVisible();
      await expect(page.getByText("Belum lulus")).toBeVisible();
    }

    // Record state before replaying the completed request.
    const stateBeforeReplayResponse = await request.get(
      `${apiBaseURL}/api/v1/execution/state`,
    );

    expect(stateBeforeReplayResponse.status()).toBe(200);

    const stateBeforeReplay = await stateBeforeReplayResponse.json();

    // Repeat the exact same payload and key; do not create a new key.
    const replayResponse = await request.post(
      `${apiBaseURL}/api/v1/execution/plan-run`,
      {
        data: payload,
        headers: {
          "Idempotency-Key": idempotencyKey,
        },
      },
    );

    expect(
      replayResponse.status(),
      "Replaying the same completed request should succeed.",
    ).toBe(200);

    const replayResult = await replayResponse.json();

    expect(replayResult.idempotency).toEqual({
      key: idempotencyKey,
      replayed: true,
    });

    // The replay must return the original result.
    expect(replayResult.goal).toEqual(firstResult.goal);
    expect(replayResult.execution).toEqual(firstResult.execution);

    // Replaying must not change the simulation state again.
    const stateAfterReplayResponse = await request.get(
      `${apiBaseURL}/api/v1/execution/state`,
    );

    expect(stateAfterReplayResponse.status()).toBe(200);

    const stateAfterReplay = await stateAfterReplayResponse.json();

    expect(stateAfterReplay.state).toEqual(stateBeforeReplay.state);
  });
});

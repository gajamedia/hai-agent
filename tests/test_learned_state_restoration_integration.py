def test_restored_calibrated_influence_is_available_for_next_decision(
    tmp_path,
):
    agent1 = build_agent(
        tmp_path
    )

    agent1.self_awareness.decision_influence = (
        make_influence()
    )

    goal = SimpleNamespace(
        description="next decision",
        target_state={},
        completed=False,
        is_satisfied=lambda world_state: False,
        complete=lambda: None,
    )

    agent1.decide_and_act(
        goal=goal,
        world_state={},
    )

    agent2 = build_agent(
        tmp_path
    )

    restoration = (
        agent2.restore_learned_state()
    )

    assert restoration.fully_restored

    captured = {}

    original_evaluate = (
        agent2.self_aware_decision_arbiter
        .evaluate
    )

    def capture_evaluate(
        decision,
        influence,
    ):
        captured["influence"] = influence

        return original_evaluate(
            decision,
            influence,
        )

    agent2.self_aware_decision_arbiter.evaluate = (
        capture_evaluate
    )

    agent2.decide_and_act(
        goal=goal,
        world_state={},
    )

    assert (
        captured["influence"]
        is agent2.last_calibrated_self_aware_influence
    )



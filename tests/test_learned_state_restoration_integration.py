def test_reset_learned_state_runtime_does_not_delete_persistence(
    tmp_path,
):
    agent = build_agent(
        tmp_path
    )

    agent.self_awareness.decision_influence = (
        make_influence()
    )

    goal = SimpleNamespace(
        description="runtime reset",
        target_state={},
        completed=False,
        is_satisfied=lambda world_state: False,
        complete=lambda: None,
    )

    agent.decide_and_act(
        goal=goal,
        world_state={},
    )

    persisted = (
        agent
        .get_calibrated_self_awareness_persistence()
    )

    assert persisted is not None

    agent.reset_learned_state_runtime()

